function transform(rows: string[], variant: number): string[] {
  let out = rows.slice()
  if (variant & 1) out = out.map((r) => [...r].reverse().join(''))
  if (variant & 2) out = out.reverse()
  if (variant & 4) out = out.map((_, x) => out.map((r) => r[x]).join(''))
  return out
}

/** Level n (1-based). Past the drawn set, the bigger pictures return mirrored/rotated (still unique). */
export function puzzleAt(n: number): NonoPuzzle {
  if (n <= PUZZLES.length) return PUZZLES[n - 1]
  const first = 20
  const pool = PUZZLES.length - first
  const k = n - PUZZLES.length - 1
  const base = PUZZLES[first + (k % pool)]
  return { name: base.name, rows: transform(base.rows, 1 + (Math.floor(k / pool) % 7)) }
}
